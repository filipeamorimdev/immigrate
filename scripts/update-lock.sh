#!/usr/bin/env bash
# Rebuilds requirements.lock from pyproject.toml in a clean environment.
#
# It runs in the Dockerfile's base image, so the lock lists what the image needs. Run on
# a Mac, pip would otherwise add macOS-only packages that the Linux image can't install.
set -euo pipefail

cd "$(dirname "$0")/.."
base="$(sed -n 's/^FROM \([^ ]*\).*/\1/p' Dockerfile | head -n 1)"
frozen="$(mktemp)"
trap 'rm -f "$frozen"' EXIT

docker run --rm -v "$PWD":/src:ro "$base" sh -euc '
  mkdir /work
  cp -r /src/pyproject.toml /src/README.md /src/src /work/
  python3 -m venv /venv
  /venv/bin/pip install --quiet --disable-pip-version-check /work
  /venv/bin/pip freeze --exclude immigrate
' > "$frozen"

{
  echo "# Generated by scripts/update-lock.sh. Don't edit by hand."
  cat "$frozen"
} > requirements.lock
echo "Wrote requirements.lock using $base."
